/**
 * MiniBar 账号库 —— 多账号 token 持久化与 Windows 凭据 swap。
 *
 * 存储：
 *  - 库文件：~/.gemini/antigravity/sidecar_data/agy-minibar/accounts.json
 *    结构 { version, accounts: [{ email, token, auth_method, writer_id, savedAt }] }
 *  - 活跃凭据：Windows Credential Manager `gemini:antigravity`
 *    （blob JSON: { token, auth_method, id_token_email, writer_id }）
 *
 * 安全：库文件位于用户目录，权限收窄到当前用户（Windows 上尽力而为）。
 */

import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';

const DATA_DIR = join(homedir(), '.gemini', 'antigravity', 'sidecar_data');
const LIB_DIR = join(DATA_DIR, 'agy-minibar');
const ACCOUNTS_FILE = join(LIB_DIR, 'accounts.json');
const CRED_TARGET = 'gemini:antigravity';

export function loadLibrary() {
  try {
    if (!existsSync(ACCOUNTS_FILE)) return { version: 1, accounts: [] };
    const j = JSON.parse(readFileSync(ACCOUNTS_FILE, 'utf-8'));
    if (!j || !Array.isArray(j.accounts)) return { version: 1, accounts: [] };
    return j;
  } catch {
    return { version: 1, accounts: [] };
  }
}

export function saveLibrary(lib) {
  mkdirSync(LIB_DIR, { recursive: true });
  const tmp = ACCOUNTS_FILE + '.tmp';
  writeFileSync(tmp, JSON.stringify(lib, null, 2), 'utf-8');
  renameSync(tmp, ACCOUNTS_FILE);
  try { chmodSync(ACCOUNTS_FILE, 0o600); } catch { /* Windows 尽力而为 */ }
}

export function upsertAccount({ email, token, auth_method, writer_id }) {
  if (!email || typeof email !== 'string' || !email.includes('@')) throw new Error('invalid email: ' + email);
  // token 允许两种形态：字符串（旧格式）或对象 { access_token, refresh_token, ... }（桌面版真实格式）
  const tokenOk = (typeof token === 'string' && token.length >= 32) ||
    (token && typeof token === 'object' && typeof token.access_token === 'string' && token.access_token.length >= 20);
  if (!tokenOk) throw new Error('invalid token for ' + email);
  const lib = loadLibrary();
  const now = Date.now();
  const hit = lib.accounts.find(a => a.email === email);
  if (hit) {
    hit.token = token;
    hit.auth_method = auth_method || hit.auth_method;
    hit.writer_id = writer_id || hit.writer_id;
    hit.savedAt = now;
  } else {
    lib.accounts.push({ email, token, auth_method: auth_method || 'consumer', writer_id: writer_id || '', savedAt: now });
  }
  saveLibrary(lib);
  return lib;
}

export function getAccount(email) {
  if (!email || typeof email !== 'string') return null;
  // 严格相等 + trim，避免大小写差异导致取错账号
  const want = String(email).trim().toLowerCase();
  return loadLibrary().accounts.find(a => String(a.email).toLowerCase() === want) || null;
}

/* ---------------- PowerShell 凭据操作 ---------------- */

const PS_SCRIPT = join(LIB_DIR, 'credswap.ps1');

function ensurePsScript() {
  mkdirSync(LIB_DIR, { recursive: true });
  const script = `# Auto-generated by agy-minibar. Read/write 'gemini:antigravity' credential blob.
param([string]$Mode, [string]$Email, [string]$TokenJson, [string]$OutFile)
Add-Type -TypeDefinition @"
using System;
using System.Runtime.InteropServices;
public class AGYCred {
  [DllImport("advapi32.dll", EntryPoint="CredReadW", CharSet=CharSet.Unicode, SetLastError=true)]
  public static extern bool CredRead(string target, int type, int flags, out IntPtr credPtr);
  [DllImport("advapi32.dll", EntryPoint="CredWriteW", CharSet=CharSet.Unicode, SetLastError=true)]
  public static extern bool CredWrite(ref CREDENTIAL cred, int flags);
  [DllImport("advapi32.dll")]
  public static extern void CredFree(IntPtr cred);
  [StructLayout(LayoutKind.Sequential, CharSet=CharSet.Unicode)]
  public struct CREDENTIAL {
    public int Flags; public int Type; public string TargetName; public string Comment;
    public System.Runtime.InteropServices.ComTypes.FILETIME LastWritten;
    public int CredentialBlobSize; public IntPtr CredentialBlob; public int Persist;
    public int AttributeCount; public IntPtr Attributes; public string TargetAlias; public string UserName;
  }
}
"@
function Read-Blob {
  $p = [IntPtr]::Zero
  if (-not [AGYCred]::CredRead('gemini:antigravity', 1, 0, [ref]$p)) { throw "CredRead failed: $([Runtime.InteropServices.Marshal]::GetLastWin32Error())" }
  $c = [Runtime.InteropServices.Marshal]::PtrToStructure($p, [type][AGYCred+CREDENTIAL])
  $bytes = New-Object byte[] $c.CredentialBlobSize
  [Runtime.InteropServices.Marshal]::Copy($c.CredentialBlob, $bytes, 0, $c.CredentialBlobSize)
  [AGYCred]::CredFree($p)
  [Text.Encoding]::UTF8.GetString($bytes)
}
function Write-Blob($json) {
  $bytes = [Text.Encoding]::UTF8.GetBytes($json)
  $ptr = [Runtime.InteropServices.Marshal]::AllocHGlobal($bytes.Length)
  [Runtime.InteropServices.Marshal]::Copy($bytes, 0, $ptr, $bytes.Length)
  $c = New-Object AGYCred+CREDENTIAL
  $c.Flags = 0; $c.Type = 1
  $c.TargetName = 'gemini:antigravity'
  $c.Comment = 'managed by agy-minibar'
  $c.CredentialBlobSize = $bytes.Length
  $c.CredentialBlob = $ptr
  $c.Persist = 2  # Local machine
  $c.AttributeCount = 0; $c.Attributes = [IntPtr]::Zero
  $c.TargetAlias = $null; $c.UserName = 'antigravity'
  $ok = [AGYCred]::CredWrite([ref]$c, 0)
  [Runtime.InteropServices.Marshal]::FreeHGlobal($ptr)
  if (-not $ok) { throw "CredWrite failed: $([Runtime.InteropServices.Marshal]::GetLastWin32Error())" }
}
switch ($Mode) {
  'email' { (Read-Blob | ConvertFrom-Json).id_token_email }
  'raw'   { Read-Blob }
  'write' { Write-Blob $TokenJson; 'OK' }
  'write-file' {
    $json = [IO.File]::ReadAllText($TokenJson, [Text.Encoding]::UTF8)
    if (-not $json) { throw "empty blob file" }
    # 校验 JSON 结构，防止写坏凭据
    $o = $json | ConvertFrom-Json
    if (-not $o.token -or -not $o.id_token_email) { throw "blob missing token/id_token_email" }
    Write-Blob $json; 'OK'
  }
}
`;
  writeFileSync(PS_SCRIPT, script, 'utf-8');
}

function runPs(args) {
  // pwsh 不在 PATH 时回退到 Windows PowerShell（winget 环境差异兼容）
  let exe = 'pwsh';
  try { execFileSync('pwsh', ['-NoProfile', '-Command', 'exit 0'], { timeout: 5000, windowsHide: true }); }
  catch (e) {
    if (e.code === 'ENOENT') exe = 'powershell.exe';
  }
  const out = execFileSync(exe, ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', PS_SCRIPT, ...args], {
    encoding: 'utf-8',
    timeout: 15000,
    windowsHide: true,
    maxBuffer: 4 * 1024 * 1024,
  });
  return String(out || '').trim();
}

export function readActiveEmail() {
  ensurePsScript();
  try { return runPs(['-Mode', 'email']) || null; } catch { return null; }
}

export function readActiveBlob() {
  ensurePsScript();
  try { return runPs(['-Mode', 'raw']) || null; } catch { return null; }
}

/** 通过临时文件传递 blob（避开命令行长度限制与转义炸弹） */
export function writeActiveBlobFile(filePath) {
  ensurePsScript();
  runPs(['-Mode', 'write-file', '-TokenJson', filePath]);
  return true;
}
